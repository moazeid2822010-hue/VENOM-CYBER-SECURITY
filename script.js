let language = "ar";
const $ = (id) => document.getElementById(id);
function setLanguage(next) {
  language = next;
  document.documentElement.lang = next;
  document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[next][key]) el.innerHTML = translations[next][key];
  });
  $("languageSwitch").textContent = next === "ar" ? "EN" : "عربي";
  $("menuToggle").setAttribute("aria-label", next === "ar" ? "فتح القائمة" : "Open navigation");
  $("urlInput").placeholder = next === "ar" ? "https://example.com" : "https://example.com";
  $("passwordInput").placeholder = next === "ar" ? "كلمة مرور تجريبية" : "Try a sample password";
  document.title = next === "ar" ? "VENOM | الأمن السيبراني" : "VENOM | Cyber Security";
}
