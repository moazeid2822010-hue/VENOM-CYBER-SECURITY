$("checkUrl").addEventListener("click", () => {
  const raw = $("urlInput").value.trim();
  const result = $("urlResult");
  result.className = "tool-result";
  if (!raw) {
    result.textContent = language === "ar" ? "أدخل رابطًا أولًا." : "Enter a URL first.";
    return;
  }
  let parsed;
  try {
    parsed = new URL(raw.includes("://") ? raw : "https://" + raw);
    if (!["http:", "https:"].includes(parsed.protocol)) throw new Error("protocol");
  } catch {
    result.classList.add("bad");
    result.textContent = language === "ar" ? "صيغة الرابط غير صحيحة. تحقق من العنوان." : "The URL format looks invalid. Check the address.";
    return;
  }
  const flags = [];
  if (parsed.protocol !== "https:") flags.push(language === "ar" ? "الاتصال لا يستخدم HTTPS." : "The connection does not use HTTPS.");
  if (parsed.hostname.startsWith("xn--") || parsed.hostname.includes(".xn--")) flags.push(language === "ar" ? "اسم النطاق يحتوي على ترميز قد يُستخدم لتشابه الحروف." : "The domain uses punycode, which can be used to imitate other names.");
  if (parsed.hostname.split(".").length > 5) flags.push(language === "ar" ? "اسم النطاق يحتوي على مستويات كثيرة." : "The domain has many subdomain levels.");
  if (/@/.test(raw.split("://").pop().split("/")[0])) flags.push(language === "ar" ? "وجود @ في جزء المضيف قد يخفي الوجهة الحقيقية." : "An @ in the authority section can disguise the real destination.");
  if (raw.length > 180) flags.push(language === "ar" ? "الرابط طويل بشكل غير معتاد." : "The URL is unusually long.");
  if (/(login|verify|account|secure|update|gift|free|password)/i.test(parsed.href)) flags.push(language === "ar" ? "يحتوي على كلمات شائعة في روابط الطُعم؛ ليست دليلًا وحدها." : "Contains words often seen in bait links; this alone is not proof.");
  if (flags.length) {
    result.classList.add("warn");
    result.textContent = (language === "ar" ? "مؤشرات تستحق الانتباه: " : "Signals to review: ") + flags.join(" ");
  } else {
    result.classList.add("good");
    result.textContent = language === "ar" ? "لم تُكتشف مؤشرات واضحة في الفحص البسيط. هذا لا يعني أن الرابط آمن؛ تحقق من النطاق من مصدر موثوق." : "No obvious signals found in this basic check. That does not mean the URL is safe; verify the domain independently.";
  }
});

$("checkPassword").addEventListener("click", () => {
  const value = $("passwordInput").value;
  const result = $("passwordResult");
  result.className = "tool-result";
  if (!value) {
    result.textContent = language === "ar" ? "أدخل كلمة تجريبية فقط." : "Enter a sample password only.";
    return;
  }
  let score = 0;
  if (value.length >= 12) score++;
  if (/[a-z]/.test(value) && /[A-Z]/.test(value)) score++;
  if (/\d/.test(value)) score++;
  if (/[^A-Za-z0-9]/.test(value)) score++;
  if (value.length >= 16) score++;
  result.classList.add(score >= 4 ? "good" : score >= 2 ? "warn" : "bad");
  const label = language === "ar"
    ? (score >= 4 ? "خصائص جيدة مبدئيًا" : score >= 2 ? "تحتاج إلى تحسين" : "ضعيفة حسب هذه المؤشرات")
    : (score >= 4 ? "Good characteristics (basic check)" : score >= 2 ? "Could be improved" : "Weak by these basic signals");
  result.textContent = `${label} — ${score}/5. ` + (language === "ar" ? "لا تستخدم كلمة مرور حقيقية هنا؛ الطول والتفرّد مهمان." : "Do not use a real password here; length and uniqueness matter.");
  $("passwordInput").value = "";
});

function updateChecklist() {
  const boxes = [...document.querySelectorAll(".check-item input")];
  const checked = boxes.filter(box => box.checked).length;
  $("checkProgress").style.width = `${checked / boxes.length * 100}%`;
  $("progressText").textContent = `${checked} / ${boxes.length}`;
}
document.querySelectorAll(".check-item input").forEach(box => box.addEventListener("change", updateChecklist));
